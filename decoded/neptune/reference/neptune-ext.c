/// \file
/// The translation unit CMake compiles for the `neptunec1-ext` target. It
/// exists only to stitch the generated code and the hand-written ROM
/// replacement into one TU.
///
/// This is the *extern* variant. The plain `neptunec1` target is built from
/// the self-contained `as-generated/neptunec1.c`, which decompiles the ROM
/// alongside the game; that is the reference build the golden traces were
/// recorded from, and the control this variant is checked against. Both are
/// generated by scripts/decompile.sh and both are gated by scripts/verify.sh
/// against the same traces, which is what proves the hand-written
/// `rom_mon_wait` behaves identically to the decompiled original -- cycle
/// counts included.
///
/// ### Why a wrapper is necessary
///
/// `apple2tc/system2-inc.h` does not merely declare the emulated machine, it
/// *defines* it, and nearly all of it has internal linkage: the registers and
/// flags (`s_a`, `s_status_*`), the RAM array, the cycle counters, and the
/// access helpers (`push8`, `pop8`, `push16`, `pop16`). The `CYCLES` macro
/// expands to references to those statics plus the caller's local
/// `branchTarget`. `rom.c` also uses the generated statics `ovf8()` and
/// `sbc_dec16()`.
///
/// So `rom.c` cannot be its own object file; it has to share a translation
/// unit with the generated code, and the generated file must come first.

#include "neptunec1-ext.c"

#include "rom.c"
